const replacements: [string, string][] = Object.entries(fa)
  .filter(([key]) => key.length > 12)
  .sort(([a], [b]) => b.length - a.length);

export function translateText(value: string, language: UiLanguage = 'fa'): string {
  if (language === 'en' || !value) return value;
  const exact = fa[value.trim()];
  if (exact) return value.replace(value.trim(), exact);
  let translated = value;
  for (const [source, target] of replacements) {
    if (translated.includes(source)) translated = translated.split(source).join(target);
  }
  const prefixes: [string, string][] = [['Estimated units today:', 'واحد تخمینی امروز:'], ['Requests today:', 'درخواست‌های امروز:'], ['Region:', 'منطقه:'], ['Languages:', 'زبان‌ها:'], ['Source:', 'منبع:'], ['Published ', 'منتشرشده '], ['Confidence:', 'میزان اطمینان:'], ['Follow-up search:', 'جست‌وجوی تکمیلی:'], ['Feeds represented:', 'خوراک‌های خبری حاضر:'], ['Independent publisher groups:', 'گروه‌های مستقل ناشر:'], ['Duplicate stories merged:', 'خبرهای تکراری ادغام‌شده:'], ['Undated:', 'بدون تاریخ:'], ['Older than 90 days:', 'قدیمی‌تر از ۹۰ روز:'], ['Direction:', 'جهت روند:'], ['Monthly observations:', 'تعداد داده‌های ماهانه:'], ['Recent change between halves of the returned series:', 'تغییر بین نیمه اول و دوم داده‌های دریافت‌شده:'], ['Potential anomaly:', 'ناهنجاری احتمالی:'], ['Research gap:', 'کمبود تحقیق:'], ['Shared terms across publisher and video samples:', 'واژه‌های مشترک میان نمونه خبرها و ویدئوها:'], [' · Independent publisher groups:', ' · گروه‌های ناشر مستقل:'], [' · Undated:', ' · بدون تاریخ:'], [' · Older than 90 days:', ' · قدیمی‌تر از ۹۰ روز:'], ['Potential discrepancy:', 'اختلاف احتمالی:'], ['The website returned HTTP ', 'وب‌سایت پاسخ HTTP ']];
  for (const [source, target] of prefixes) if (translated.startsWith(source)) translated = target + translated.slice(source.length);
  return translated;
}

function flattenText(node: ReactNode): string {
  if (typeof node === 'string' || typeof node === 'number') return String(node);
  if (Array.isArray(node)) return node.map(flattenText).join(' ');
  if (isValidElement(node)) return flattenText((node.props as { children?: ReactNode }).children);
  return '';
}

const RTL_STRONG = /[\u05D0-\u05EA\u05EF-\u05F2\u0620-\u064A\u066E-\u066F\u0671-\u06D3\u06FA-\u06FC\u06FF\u0750-\u077F\u08A0-\u08C9\uFB1D-\uFB4F\uFB50-\uFDFF\uFE70-\uFEFC]/u;
const LTR_STRONG = /[A-Za-z\u00C0-\u02AF\u0370-\u052F\u0900-\u1FFF\u2C00-\uD7FF]/u;
const RTL_RUN = /[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFC](?:[\u200C\u200D]?[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFC])*(?:[ \t]+[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFC](?:[\u200C\u200D]?[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFC])*)*/gu;
const LTR_RUN = /[A-Za-z\u00C0-\u02AF\u0370-\u052F0-9]+(?:[ \t]+[A-Za-z\u00C0-\u02AF\u0370-\u052F0-9]+)*/gu;

export function resolveTextDirection(value: string): 'rtl' | 'ltr' {
  // Source text follows its first strong character, independent of the UI locale.
  for (const character of value) {
    if (RTL_STRONG.test(character)) return 'rtl';
    if (LTR_STRONG.test(character)) return 'ltr';
  }
  return 'ltr';
}

/**
 * Chooses the paragraph base direction from the actual script content.
 * A mixed sentence follows the selected UI language, while a source-only
 * English headline remains LTR even when the surrounding UI is Persian.
 */
export function resolveParagraphDirection(value: string, language: UiLanguage = 'fa'): 'rtl' | 'ltr' {
  const hasRtl = RTL_STRONG.test(value);
  const hasLtr = LTR_STRONG.test(value);
  if (hasRtl && hasLtr) return language === 'fa' ? 'rtl' : 'ltr';
  if (hasRtl) return 'rtl';
  if (hasLtr) return 'ltr';
  return language === 'fa' ? 'rtl' : 'ltr';
}

/** Wrap opposite-direction word runs with Unicode directional isolates. */
export function isolateMixedDirectionText(value: string, paragraphDirection: 'rtl' | 'ltr'): string {
  if (!value) return value;
  const pattern = paragraphDirection === 'rtl' ? LTR_RUN : RTL_RUN;
  const isolate = paragraphDirection === 'rtl' ? '\u2066' : '\u2067';
  return value.replace(pattern, (run) => isolate + run + '\u2069');
}

export function containsPersianText(node: ReactNode): boolean {
  return resolveTextDirection(flattenText(node)) === 'rtl';
}
export function resolveNodeDirection(node: ReactNode, language?: UiLanguage): 'rtl' | 'ltr' {
  const value = flattenText(node);
  return language ? resolveParagraphDirection(value, language) : resolveTextDirection(value);
}

export function isolateMixedDirectionNode(node: ReactNode, paragraphDirection: 'rtl' | 'ltr'): ReactNode {
  if (typeof node === 'string' || typeof node === 'number') {
    return isolateMixedDirectionText(String(node), paragraphDirection);
  }
  if (Array.isArray(node)) return node.map((child) => isolateMixedDirectionNode(child, paragraphDirection));
  if (!isValidElement<{ children?: ReactNode }>(node)) return node;
  return cloneElement(node, {
    children: isolateMixedDirectionNode(node.props.children, paragraphDirection),
  });
}

export function translateNode(node: ReactNode, language: UiLanguage): ReactNode {
  if (typeof node === 'string') return translateText(node, language);
  if (Array.isArray(node)) return node.map((child) => translateNode(child, language));
  if (!isValidElement(node)) return node;
  const elementType = node.type as { displayName?: string; name?: string };
  if (/^Source(?:Text|Heading|Title)$/.test(elementType.displayName ?? elementType.name ?? '')) return node;
  const props = node.props as Record<string, unknown>;
  const children = translateNode(props.children as ReactNode, language);
  const patch: Record<string, unknown> = { children };
  if (props.ListHeaderComponent && typeof props.ListHeaderComponent !== 'function') {
    patch.ListHeaderComponent = translateNode(props.ListHeaderComponent as ReactNode, language);
  }
  if (props.ListEmptyComponent && typeof props.ListEmptyComponent !== 'function') {
    patch.ListEmptyComponent = translateNode(props.ListEmptyComponent as ReactNode, language);
  }
  if (props.ListFooterComponent && typeof props.ListFooterComponent !== 'function') {
    patch.ListFooterComponent = translateNode(props.ListFooterComponent as ReactNode, language);
  }
  if (/^Text$/.test(elementType.displayName ?? elementType.name ?? '')) {
    const content = flattenText(children);
    const direction = resolveParagraphDirection(content, language);
    patch.children = isolateMixedDirectionNode(children, direction);
    patch.style = [props.style, { writingDirection: direction, textAlign: direction === 'rtl' ? 'right' : 'left' }];
  }
  return cloneElement(node, patch);
}
